
% Υλοποίηση μέγιστης καθόδου με προβολή.
function [x_hist, f_hist, k] = steepest_descent_projection(f, grad_f, x0, s_k, gamma_k, epsilon, max_iter, x_min, x_max)

    x_curr = x0;
    x_hist = x_curr;
    f_hist = f(x_curr);
    
    for k = 1:max_iter
        
        % 1. Υπολογισμός Κλίσης.
        g_k = grad_f(x_curr);
        
        % 2. Υπολογισμός Προβολής (Bar_x_k).
        % w_k = x_k - s_k * grad f(x_k)
        w_k = x_curr - s_k * g_k;
        
        % Προβολή του w_k στο ορθογώνιο κουτί.
        % Η εντολή min/max δουλεύει στοιχείο προς στοιχείο.
        bar_x_k = min(max(w_k, x_min), x_max);
        
        % 3. Κριτήριο Τερματισμού για Μεθόδους Προβολής
        % Σταματάμε αν δεν κουνηθήκαμε καθόλου ή αν η αλλαγή είναι πολύ μικρή
        % Ή αν η νόρμα της κλίσης είναι μικρή (αν είμαστε εντός περιοχής).
        
        % Κλασικό κριτήριο εργασίας: ||grad f|| < epsilon (όταν είμαστε μέσα)
        % ΑΛΛΑ, στις μεθόδους προβολής, συχνά ελέγχουμε την απόσταση ||x_k+1 - x_k||
        % Θα χρησιμοποιήσουμε το κριτήριο που ζητάει η άσκηση (epsilon = 0.01)
        % Θα ελέγχουμε την "προβαλλόμενη κλίση" ή απλά την κλίση αν δεν είμαστε στο όριο.
        
        % Για απλότητα και συμβατότητα με την εκφώνηση, θα ελέγξουμε την κλίση,
        % αλλά θα προσθέσουμε και έλεγχο στασιμότητας.
        
        if norm(bar_x_k - x_curr) < 1e-6 && k > 1
             % Αν το projected point είναι ίδιο με το τρέχον, κολλήσαμε.
             break;
        end
        
        % 4. Ενημέρωση Σημείου.
        % x_{k+1} = x_k + gamma_k * (bar_x_k - x_k)
        x_next = x_curr + gamma_k * (bar_x_k - x_curr);
        
        % Αποθήκευση.
        x_curr = x_next;
        x_hist = [x_hist, x_curr];
        f_hist = [f_hist, f(x_curr)];
        
        % Έλεγχος τερματισμού με βάση την άσκηση (αν και για προβολή είναι λίγο ασαφές)
        % Συνήθως ελέγχουμε |x_next - x_prev| < epsilon.
        if norm(grad_f(x_curr)) < epsilon
             break;
        end
    end
end